#!/usr/bin/env python3
"""Generates loader/src/registry/vanilla_abilities.inc from the verified cube::AbilityId enum in
sdk/include/cubeworld/types.h (written by `kmap export`): {number, lowercase name}."""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
text = open(os.path.join(here, '..', 'sdk', 'include', 'cubeworld', 'types.h')).read()
rows = sorted((int(n), name.lower()) for name, n in re.findall(r'cube_AbilityId_(\w+) = (\d+),', text))
assert [n for n, _ in rows] == list(range(111)), 'cube::AbilityId must hold 0..110'
out = os.path.join(here, '..', 'loader', 'src', 'registry', 'vanilla_abilities.inc')
with open(out, 'w', newline='\n') as f:
    f.write('// Generated by scripts/gen_vanilla_abilities.py: {number, name} of cube::AbilityId for Cube.exe build 0x51D2CE9C.\n')
    for n, name in rows:
        f.write(f'{{{n}, "{name}"}},\n')
print(f'wrote {out}: {len(rows)} abilities')
