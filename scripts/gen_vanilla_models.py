#!/usr/bin/env python3
"""Generates loader/src/registry/vanilla_models.inc from tools/cwmod/model_slots.json
(slot numbers extracted from Cube.exe ModelLoader::loadAll)."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
slots = json.load(open(os.path.join(here, '..', 'tools', 'cwmod', 'model_slots.json')))
rows = sorted((s, name) for name, ss in slots.items() for s in ss)
out = os.path.join(here, '..', 'loader', 'src', 'registry', 'vanilla_models.inc')
with open(out, 'w') as f:
    f.write('// Generated by scripts/gen_vanilla_models.py: {slot, asset key} for Cube.exe build 0x51D2CE9C.\n')
    for s, n in rows:
        f.write(f'{{{s}, "{n}"}},\n')
print(f'wrote {out}: {len(rows)} slots')
