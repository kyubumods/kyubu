#!/usr/bin/env python3
"""Regenerate loader/src/core/zlib1.def from a game's original zlib1.dll.

usage: gen_zlib_def.py <path to original zlib1.dll>
"""
import sys, os
import pefile

pe = pefile.PE(sys.argv[1])
out = os.path.join(os.path.dirname(__file__), '..', 'loader', 'src', 'core', 'zlib1.def')
lines = ['; Generated by scripts/gen_zlib_def.py from the zlib 1.2.3 build shipped with Cube World Alpha.',
         '; Every export is forwarded, by name and by its original ordinal, to zlib1_vanilla.dll.',
         'LIBRARY zlib1', 'EXPORTS']
for e in sorted(pe.DIRECTORY_ENTRY_EXPORT.symbols, key=lambda e: e.ordinal):
    n = e.name.decode()
    lines.append(f'  {n} = zlib1_vanilla.{n} @{e.ordinal}')
open(out, 'w').write('\n'.join(lines) + '\n')
print(f'wrote {out} ({len(lines) - 4} exports)')
