def test_common_split(tmp_path):
    src = tmp_path / 'm' / 'src'
    (src / 'logic').mkdir(parents=True)
    (src / 'lib').mkdir()
    (src / 'main.lua').write_text('local l = require("m.logic.a"); local f = require("m.lib.fx")\n', encoding='utf-8')
    (src / 'logic' / 'a.lua').write_text('return { v = 1 }\n', encoding='utf-8')
    (src / 'lib' / 'fx.lua').write_text('return { v = 2 }\n', encoding='utf-8')
    (src / 'common.txt').write_text('# pure\nlogic.*\n', encoding='utf-8')
    (tmp_path / 'm' / 'mod.toml').write_text('id = "m"\n', encoding='utf-8')
    assert bundle_lua.main(['--mod', str(tmp_path / 'm')]) == 0
    common = (tmp_path / 'm' / 'scripts' / 'common.lua').read_text(encoding='utf-8')
    client = (tmp_path / 'm' / 'scripts' / 'client.lua').read_text(encoding='utf-8')
    assert 'preload["m.logic.a"]' in common and 'preload["m.lib.fx"]' not in common and 'require("m.main")' not in common
    assert 'preload["m.lib.fx"]' in client and 'preload["m.logic.a"]' not in client and client.endswith('require("m.main")\n')
    assert bundle_lua.main(['--mod', str(tmp_path / 'm'), '--check']) == 0
    (src / 'common.txt').write_text('nothing.*\n', encoding='utf-8')
    with pytest.raises(SystemExit):
        bundle_lua.main(['--mod', str(tmp_path / 'm')])


def test_server_split(tmp_path):
    # src/server/ modules are server-only: they leave client.lua and go to server.lua with the modules of server.txt
    src = tmp_path / 'm' / 'src'
    for d in ('logic', 'lib', 'server'):
        (src / d).mkdir(parents=True)
    w = lambda rel, text: (src / rel).write_text(text + chr(10), encoding='utf-8')
    w('main.lua', 'local f = require("m.lib.fx")')
    w('logic/a.lua', 'return { v = 1 }')
    w('lib/fx.lua', 'return { v = 2 }')
    w('lib/combat.lua', 'return { v = 3 }')
    w('server/main.lua', 'local c = require("m.lib.combat"); local a = require("m.logic.a")')
    w('common.txt', 'logic.*')
    w('server.txt', '# shared' + chr(10) + 'lib.combat')
    (tmp_path / 'm' / 'mod.toml').write_text('id = "m"' + chr(10), encoding='utf-8')
    assert bundle_lua.main(['--mod', str(tmp_path / 'm')]) == 0
    read = lambda n: (tmp_path / 'm' / 'scripts' / n).read_text(encoding='utf-8')
    server, client, common = read('server.lua'), read('client.lua'), read('common.lua')
    assert 'preload["m.server.main"]' in server and 'preload["m.lib.combat"]' in server
    assert 'preload["m.lib.fx"]' not in server and 'preload["m.logic.a"]' not in server
    assert server.endswith('require("m.server.main")' + chr(10))
    assert 'preload["m.server.main"]' not in client and 'preload["m.lib.combat"]' in client
    assert client.endswith('require("m.main")' + chr(10))
    assert 'preload["m.logic.a"]' in common
    assert bundle_lua.main(['--mod', str(tmp_path / 'm'), '--check']) == 0
    w('server.txt', 'nothing.*')
    with pytest.raises(SystemExit):
        bundle_lua.main(['--mod', str(tmp_path / 'm')])
