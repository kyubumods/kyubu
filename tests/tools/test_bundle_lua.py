"""tools/bundle_lua.py (change add-skills-unleashed, task 2.2) and the shape of mods-gameplay/skills_unleashed (task 2.1).

The bundle is run in a LuaJIT when one is found (KYUBU_LUAJIT, PATH, or the luajit built next to the loader), and
compared as text otherwise. The freshness test is the one that fails when someone edits src/ and forgets the bundler.
"""
import glob
import os
import shutil
import subprocess
import sys

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import bundle_lua  # noqa: E402

MOD = os.path.join(ROOT, 'mods-gameplay', 'skills_unleashed')


def find_luajit():
    cands = [os.environ.get('KYUBU_LUAJIT'), shutil.which('luajit')]
    cands += glob.glob(os.path.join(ROOT, 'build', 'luajit-build', 'src', 'luajit*'))
    cands += glob.glob(os.path.join(ROOT, '..', '..', '..', 'toolchains', 'kyubu-mingw-c', 'luajit-build', 'src', 'luajit.exe'))
    for c in cands:
        if c and os.path.isfile(c):
            try:
                r = subprocess.run([c, '-e', 'io.write("ok")'], capture_output=True, text=True, timeout=20)
            except (OSError, subprocess.SubprocessError):
                continue
            if r.returncode == 0 and r.stdout == 'ok':
                return c
    return None


LUAJIT = find_luajit()


def write(path, text, newline='\n'):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline=newline) as fh:
        fh.write(text)


@pytest.fixture
def tree(tmp_path):
    src = tmp_path / 'src'
    write(str(src / 'main.lua'),
          'local tuning = require("demo.lib.tuning")\nlocal fx = require("demo.lib.fx")\n'
          'RESULT = tuning.n + fx.double(tuning.n)\nreturn { ok = true }\n')
    write(str(src / 'lib' / 'tuning.lua'), 'return { n = 7 }\n')
    write(str(src / 'lib' / 'fx.lua'), '-- a trailing comment is not a problem\nlocal M = {}\nfunction M.double(x) return x * 2 end\nreturn M\n-- end')
    write(str(src / 'abilities' / 'berserker.lua'), 'return {}\n')
    return src


def test_module_names_follow_the_path(tree):
    names = bundle_lua.module_names(str(tree), 'demo')
    assert sorted(names) == ['demo.abilities.berserker', 'demo.lib.fx', 'demo.lib.tuning', 'demo.main']


def test_bundle_is_deterministic_and_marks_each_module(tree):
    a = bundle_lua.bundle(str(tree), 'demo')
    assert a == bundle_lua.bundle(str(tree), 'demo')
    assert a.startswith('-- GENERATED by tools/bundle_lua.py')
    assert a.rstrip().endswith('require("demo.main")')
    assert a.index('-- @module demo.abilities.berserker') < a.index('-- @module demo.lib.fx') < a.index('-- @module demo.main')
    assert '\r' not in a


def test_crlf_sources_are_written_with_lf(tree):
    write(str(tree / 'lib' / 'tuning.lua'), 'return {\r\n  n = 7,\r\n}\r\n', newline='')
    assert '\r' not in bundle_lua.bundle(str(tree), 'demo')


@pytest.mark.skipif(LUAJIT is None, reason='no LuaJIT found (KYUBU_LUAJIT, PATH, or the loader build)')
def test_bundle_runs_and_modules_see_each_other(tree, tmp_path):
    out = tmp_path / 'client.lua'
    out.write_text(bundle_lua.bundle(str(tree), 'demo'), encoding='utf-8', newline='\n')
    r = subprocess.run([LUAJIT, '-e', 'dofile(%r); io.write(tostring(RESULT))' % str(out).replace('\\', '/')],
                       capture_output=True, text=True, timeout=30)
    assert r.returncode == 0, r.stderr
    assert r.stdout == '21'


def test_check_passes_when_current_and_fails_when_stale(tree, tmp_path):
    out = tmp_path / 'scripts' / 'client.lua'
    assert bundle_lua.main(['--src', str(tree), '--prefix', 'demo', '--out', str(out)]) == 0
    assert bundle_lua.main(['--src', str(tree), '--prefix', 'demo', '--out', str(out), '--check']) == 0
    write(str(tree / 'lib' / 'tuning.lua'), 'return { n = 8 }\n')
    assert bundle_lua.main(['--src', str(tree), '--prefix', 'demo', '--out', str(out), '--check']) == 1


def test_check_fails_when_the_output_is_missing(tree, tmp_path):
    assert bundle_lua.main(['--src', str(tree), '--prefix', 'demo', '--out', str(tmp_path / 'none.lua'), '--check']) == 1


def test_a_bad_module_name_and_a_missing_entry_are_refused(tree):
    write(str(tree / 'Bad-Name.lua'), 'return 1\n')
