def manifest():
    try:
        import tomllib
    except ImportError:  # Python before 3.11
        pytest.skip('tomllib needs Python 3.11')
    with open(os.path.join(MOD, 'mod.toml'), 'rb') as fh:
        return tomllib.load(fh)


@pytest.mark.skipif(not os.path.isdir(MOD), reason='SkillsUnleashed is in its own repository')
def test_skills_unleashed_manifest():
    # covers: skills-unleashed-mod/One package that depends on EMTweaks: EMTweaks is missing (the manifest half)
    m = manifest()
    assert m['id'] == 'skills_unleashed'
    assert m['name'] == 'SkillsUnleashed'
    assert m['kyubu'] == '^1.4'
    assert m['sides'] == ['client', 'server']      # the server side runs the server abilities (src/server/)
    assert m['trust'] == 'full'
    assert m['dependencies'] == {'emtweaks': '^0.1'}
    assert m['scripts'] == {'common': 'scripts/common.lua', 'client': 'scripts/client.lua', 'server': 'scripts/server.lua'}
    for side in ('common', 'client', 'server'):
        assert os.path.isfile(os.path.join(MOD, m['scripts'][side]))


