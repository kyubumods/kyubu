#!/usr/bin/env python3
"""Bundle a mod's Lua sources into the one script the loader runs.

The loader runs one `common` and one `client` script per mod and only puts `kyubu/lua` on `require`'s path, so a mod
cannot `require` its own files. This tool writes each `<src>/**/*.lua` into `package.preload["<prefix>.<path>"]` and ends
with `require("<prefix>.<entry>")`. The Lua state is shared by every mod, hence the prefix.

    bundle_lua.py --mod mods-gameplay/skills_unleashed      src/ -> scripts/client.lua, prefix = the id in mod.toml
    bundle_lua.py --src DIR --prefix NAME --out FILE          the same with the three paths given by hand
    bundle_lua.py ... --check        exit 1 when the output file is not what the sources produce (the freshness test)

Split into common and client: when <src>/common.txt exists (one module name per line, relative to the prefix, `*` matches
any characters, `#` starts a comment), `--mod` writes the matching modules to scripts/common.lua (preloads only, no entry:
the loader runs common on every side, the server included) and the others to scripts/client.lua. A module in common must
not call the game: the unit tests run common.lua in a Lua state that has no `kyubu` and no FFI.

Server script: when <src>/server/ holds modules (`<prefix>.server.*`), they are server-only: they leave client.lua and go to
scripts/server.lua with the modules <src>/server.txt lists (the same glob rules; they stay in client.lua too, as the two
scripts run in different processes) and the entry `server.main`. common.lua is loaded before it and gives it the pure modules.

The output is deterministic (modules sorted by name, LF endings), so a diff of it is a diff of the sources.
Module `<prefix>.lib.fx` is `<src>/lib/fx.lua`; `<prefix>.main` is `<src>/main.lua`, the default entry.
"""
import argparse
import os
import re
import sys

HEADER = """-- GENERATED by tools/bundle_lua.py from {src}/ -- do not edit this file, edit the sources and run the bundler again.
-- {count} module(s), {entry}. Each one is a package.preload entry; an error inside one names its
-- source file in the `-- @module` line above it.
"""
NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")


def module_names(src, prefix):
    """{module name: path} for every .lua file under src."""
    found = {}
    for root, dirs, files in os.walk(src):
        dirs.sort()
        for f in sorted(files):
            if not f.endswith(".lua"):
                continue
            rel = os.path.relpath(os.path.join(root, f), src)[:-4]
            parts = rel.replace(os.sep, "/").split("/")
            for p in parts:
                if not NAME_RE.match(p):
                    raise SystemExit(f"bundle_lua: '{rel}': '{p}' is not a lower-case Lua module name part")
            found[prefix + "." + ".".join(parts)] = os.path.join(root, f)
    return found


def mod_id(mod_dir):
    """The `id` of <mod_dir>/mod.toml (a plain line scan: the manifest rule makes it a simple string)."""
    with open(os.path.join(mod_dir, "mod.toml"), encoding="utf-8") as fh:
        for line in fh:
            m = re.match(r'\s*id\s*=\s*"([^"]+)"', line)
            if m:
                return m.group(1)
    raise SystemExit(f"bundle_lua: no id in {mod_dir}/mod.toml")


def read_source(path):
    with open(path, "rb") as fh:
        data = fh.read()
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as e:
        raise SystemExit(f"bundle_lua: {path}: not UTF-8 ({e})")
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if text.startswith("﻿"):
        text = text[1:]
    return text.rstrip("\n") + "\n"


def common_patterns(src):
    """The module globs of <src>/common.txt, or None when the file does not exist."""
    path = os.path.join(src, "common.txt")
    if not os.path.exists(path):
        return None
    pats = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.split("#", 1)[0].strip()
            if line:
                pats.append(line)
    return pats


def server_patterns(src):
    """The module globs of <src>/server.txt (shared client modules the server script also bundles), [] when it does not exist."""
    path = os.path.join(src, "server.txt")
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as fh:
        return [l for l in (line.split("#", 1)[0].strip() for line in fh) if l]


def split_server(client, prefix, pats):
    """(client, server): server-only modules (`server.*`) leave the client set; the server set also takes the shared globs."""
    rx = [re.compile("^" + r"\.".join(re.escape(p) for p in pat.split(".")).replace(r"\*", ".*") + "$") for pat in pats]
    only = {n: p for n, p in client.items() if n[len(prefix) + 1:].startswith("server.")}
    if not only:
        return client, None
    server = dict(only)
    for pat, r in zip(pats, rx):
        hit = {n: p for n, p in client.items() if r.match(n[len(prefix) + 1:])}
        if not hit:
            raise SystemExit(f"bundle_lua: server.txt: '{pat}' matches no module")
        server.update(hit)
    return {n: p for n, p in client.items() if n not in only}, server


def split_modules(mods, prefix, pats):
    """(common, client): the modules whose name (without the prefix) matches a glob of common.txt, and the rest."""
    rx = [re.compile("^" + r"\.".join(re.escape(p) for p in pat.split(".")).replace(r"\*", ".*") + "$") for pat in pats]
    common, client = {}, {}
    for name, path in mods.items():
        (common if any(r.match(name[len(prefix) + 1:]) for r in rx) else client)[name] = path
    for pat, r in zip(pats, rx):
        if not any(r.match(n[len(prefix) + 1:]) for n in common):
            raise SystemExit(f"bundle_lua: common.txt: '{pat}' matches no module")
    return common, client


def bundle_from(src, prefix, entry, label, mods):
    """The client script of a split: the modules not in common, then the entry."""
    text = bundle(src, prefix, entry, label, only=mods)
    return text + f'require("{prefix}.{entry}")\n'


def bundle(src, prefix, entry="main", src_label=None, only=None, common_part=False):
    """The bundled script text. `only` is a {module: path} subset (the common script); then there is no entry."""
    mods = only if only is not None else module_names(src, prefix)
    entry_name = prefix + "." + entry
    if only is None and entry_name not in module_names(src, prefix):
        raise SystemExit(f"bundle_lua: entry module {entry_name} not found under {src}")
    label = src_label or src.replace(os.sep, "/")
    out = [HEADER.format(src=label, count=len(mods), prefix=prefix, entry=("no entry" if common_part else f"entry {prefix}.{entry}"))]
    for name in sorted(mods):
        body = read_source(mods[name])
        rel = os.path.relpath(mods[name], src).replace(os.sep, "/")
        out.append(f"-- @module {name} ({rel})\n")
        out.append(f'package.preload["{name}"] = function(...)\n{body}end\n\n')
    if not common_part and only is None:
        out.append(f'require("{entry_name}")\n')
    return "".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--mod", help="a mod folder: --src <mod>/src, --prefix its id, --out <mod>/scripts/client.lua")
    ap.add_argument("--src", help="folder with the .lua sources")
    ap.add_argument("--prefix", help="module prefix, normally the mod id")
    ap.add_argument("--out", help="the generated script")
    ap.add_argument("--entry", default="main", help="entry module under the prefix (default main)")
    ap.add_argument("--label", help="source folder as written in the header (default: --src)")
    ap.add_argument("--check", action="store_true", help="do not write: fail when --out differs")
    a = ap.parse_args(argv)
    if a.mod:
        a.src = a.src or os.path.join(a.mod, "src")
        a.out = a.out or os.path.join(a.mod, "scripts", "client.lua")
        a.prefix = a.prefix or mod_id(a.mod)
        a.label = a.label or a.src.replace(os.sep, "/")
    if not (a.src and a.prefix and a.out):
        ap.error("give --mod, or all of --src, --prefix and --out")
    jobs = []  # (output path, text)
    pats = common_patterns(a.src) if a.mod else None
    if pats:
        common, client = split_modules(module_names(a.src, a.prefix), a.prefix, pats)
        jobs.append((os.path.join(a.mod, "scripts", "common.lua"), bundle(a.src, a.prefix, a.entry, a.label, only=common, common_part=True)))
        client, server = split_server(client, a.prefix, server_patterns(a.src))
        jobs.append((a.out, bundle_from(a.src, a.prefix, a.entry, a.label, client)))
        if server:
            jobs.append((os.path.join(a.mod, "scripts", "server.lua"), bundle_from(a.src, a.prefix, "server.main", a.label, server)))
    else:
        jobs.append((a.out, bundle(a.src, a.prefix, a.entry, a.label)))
    status = 0
    for out, text in jobs:
        if a.check:
            try:
                with open(out, "rb") as fh:
                    have = fh.read().decode("utf-8")
            except OSError:
                print(f"bundle_lua: {out} does not exist: run the bundler", file=sys.stderr)
                status = 1
                continue
            if have != text:
                print(f"bundle_lua: {out} is not what {a.src} produces: run the bundler", file=sys.stderr)
                status = 1
                continue
            print(f"bundle_lua: {out} is current")
            continue
        os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
        with open(out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"bundle_lua: wrote {out} ({len(text)} bytes)")
    return status


if __name__ == "__main__":
    sys.exit(main())
