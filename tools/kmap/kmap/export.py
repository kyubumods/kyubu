"""kmap export: every generated artifact, deterministically, from mapping/ (the source of truth).

  symbols/<build>.toml          loader symbol maps (signatures need the verified inputs in $KMAP_HOME)
  sdk/include/cubeworld/*.h     C headers for native mods                    (export_headers)
  loader/lua/cubeworld.lua,
  sdk/lua/cubeworld.lua         LuaJIT FFI module and LuaLS stubs            (export_lua)
  docs/game/                    reference pages                               (export_docs)
  mapping/ghidra/mappings.json  names and types for mapping/ghidra/apply.py   (export_ghidra)

kmap check regenerates everything in memory and fails on any difference. Offline (no game files), the
symbol maps are rebuilt with the signatures already committed, so everything except signatures is checked.
"""
import re
import tomllib

from . import db as dbmod
from .util import KmapError, say, toml_str, write_if_changed

GENERATED_NOTE = 'Generated by `kmap export` from mapping/ (the source of truth). Do not edit by hand: kmap check fails.'
OWNED_DIRS = ['sdk/include/cubeworld', 'docs/game']   # every file in these folders is generated
MIN_SIG = 20
MAX_SIG = 64


# --- signatures -------------------------------------------------------------------------------------------

class Signer:
    """Signatures from a verified executable: relocated dwords wildcarded, extended until unique in .text."""

    def __init__(self, data, build):
        import pefile
        self.pe = pefile.PE(data=data, fast_load=False)
        self.build = build
        text = next(s for s in self.pe.sections if s.Name.rstrip(b'\0') == b'.text')
        self.text_rva = text.VirtualAddress
        self.text = text.get_data()[:text.Misc_VirtualSize]
        self.wild = set()
        if hasattr(self.pe, 'DIRECTORY_ENTRY_BASERELOC'):
            for blk in self.pe.DIRECTORY_ENTRY_BASERELOC:
                for e in blk.entries:
                    if e.type == 3:
                        self.wild.update(range(e.rva, e.rva + 4))

    def tokens(self, va, n):
        rva = va - self.build.image_base
        data = self.pe.get_data(rva, n)
        return [None if rva + i in self.wild else b for i, b in enumerate(data)]

    def count(self, toks, limit=2):
        pat = b''.join(b'.' if t is None else re.escape(bytes([t])) for t in toks)
        rx = re.compile(b'(?=' + pat + b')', re.S)
        n = 0
        for _ in rx.finditer(self.text):
            n += 1
            if n >= limit:
                break
        return n

    def signature(self, va, min_len=MIN_SIG):
        """(signature text, unique)."""
        full = self.tokens(va, MAX_SIG)
        lo, hi = min_len, len(full)
        if self.count(full[:hi]) != 1:
            return fmt_sig(full[:min_len]), False
        while lo < hi:        # uniqueness only grows with length: binary search for the shortest
            mid = (lo + hi) // 2
            if self.count(full[:mid]) == 1:
                hi = mid
            else:
                lo = mid + 1
        return fmt_sig(full[:lo]), True


def fmt_sig(toks):
    return ' '.join('??' if t is None else f'{t:02X}' for t in toks)


def committed_signatures(ctx, bid):
    """name -> (signature, unique) from the committed symbol map (offline checks)."""
    p = ctx.repo / 'symbols' / f'{bid}.toml'
    if not p.is_file():
        return {}
    try:
        data = tomllib.loads(p.read_text(encoding='utf-8'))
    except tomllib.TOMLDecodeError:
        return {}
    return {s['name']: (s.get('signature'), s.get('unique', True)) for s in data.get('symbol', []) if 'name' in s}


def make_signer(ctx, bid):
    from .game import load_input
    build = ctx.ws.build(bid)
    return Signer(load_input(ctx, build), build)


# --- symbol maps ------------------------------------------------------------------------------------------

def symbol_map(db, bid, sign):
    """sign(entry) -> (signature or None, unique). Globals go in their own [[global]] array: they have no signature
    and lie outside .text, which symgen and the 1.0.1 loader would report for a [[symbol]]; both read only
    [[symbol]], so the array is invisible to them."""
    lines = [f'# {GENERATED_NOTE}', '# Addresses at the preferred image base 0x400000.', f'build = "{bid}"', '']
    entries = sorted((e for e in db.symbols(bid) if dbmod.exported(e)), key=lambda e: (e['address'], e['name']))
    for e in entries:
        sig, unique = sign(e)
        kind = 'global' if e['_kind'] == 'global' else e.get('kind', 'function')
        table = '[[global]]' if kind == 'global' else '[[symbol]]'
        rows = [('name', toml_str(e['name'])), ('address', f'0x{e["address"]:X}')]
        if sig:
            rows.append(('signature', toml_str(sig)))
        if not unique:
            rows.append(('unique', 'false'))
        if kind != 'global':
            rows.append(('convention', toml_str(e.get('convention', 'cdecl'))))
        rows.append(('status', toml_str(e['status'])))
        if e.get('notes'):
            rows.append(('notes', toml_str(e['notes'])))
        if kind not in ('function', 'global'):
            rows.append(('kind', toml_str(kind)))
        if e.get('prototype'):
            rows.append(('prototype', toml_str(e['prototype'])))
        if e.get('type'):
            rows.append(('type', toml_str(e['type'])))
        rows.append(('subsystem', toml_str(e['subsystem'])))
        rows.append(('evidence', '[' + ', '.join(toml_str(x) for x in e.get('evidence', [])) + ']'))
        rows.append(('source', toml_str(e['source'])))
        lines += [table] + [f'{k} = {v}' for k, v in rows] + ['']
        for alias in e.get('aliases', []):
            rows = [('name', toml_str(alias)), ('address', f'0x{e["address"]:X}')]
            if sig:
                rows.append(('signature', toml_str(sig)))
            if not unique:
                rows.append(('unique', 'false'))
            if kind != 'global':
                rows.append(('convention', toml_str(e.get('convention', 'cdecl'))))
            rows += [('status', toml_str(e['status'])), ('notes', toml_str(f'deprecated alias of {e["name"]}'))]
            lines += [table] + [f'{k} = {v}' for k, v in rows] + ['']
    return '\n'.join(lines)


def symbol_maps(ctx, db, offline):
    out = {}
    for bid in ctx.ws.builds:
        if offline:
            committed = committed_signatures(ctx, bid)

            def sign(e, committed=committed):
                sig, unique = committed.get(e['name'], (None, True))
                return sig, unique
        else:
            signer = make_signer(ctx, bid)

            def sign(e, signer=signer):
                if e['_kind'] == 'global':
                    return None, True
                return signer.signature(e['address'], max(4, min(e.get('sig_len', MIN_SIG), MIN_SIG)))
        out[f'symbols/{bid}.toml'] = symbol_map(db, bid, sign)
    return out


# --- framework ----------------------------------------------------------------------------------------------

def generate(ctx, db, offline=False):
    out = symbol_maps(ctx, db, offline)
    for mod in ('export_headers', 'export_lua', 'export_docs', 'export_ghidra'):
        try:
            m = __import__(f'kmap.{mod}', fromlist=['generate'])
        except ModuleNotFoundError as e:
            if e.name != f'kmap.{mod}':
                raise
            continue
        out.update(m.generate(ctx, db))
    return out


def stale_files(ctx, generated):
    extra = []
    for d in OWNED_DIRS:
        root = ctx.repo / d
        if root.is_dir():
            for p in sorted(root.rglob('*')):
                rel = p.relative_to(ctx.repo).as_posix()
                if p.is_file() and rel not in generated:
                    extra.append(rel)
    return extra


def check_exports(ctx, db, problems, offline=True):
    if not any((ctx.repo / 'symbols' / f'{b}.toml').is_file() for b in ctx.ws.builds) and \
            not (ctx.repo / 'mapping' / 'ghidra').exists():
        return   # nothing exported yet (fresh fixture repositories)
    try:
        gen = generate(ctx, db, offline)
    except KmapError as e:
        problems.append(dbmod.Problem('kmap export', f'cannot regenerate the artifacts: {e}'))
        return
    for rel, text in sorted(gen.items()):
        p = ctx.repo / rel
        raw = text.encode('utf-8') if isinstance(text, str) else text
        if not p.is_file():
            problems.append(dbmod.Problem(rel, 'missing: run `kmap export`'))
        elif p.read_bytes().replace(b'\r\n', b'\n') != raw:
            problems.append(dbmod.Problem(rel, 'differs from what `kmap export` generates; the source of truth is '
                                               'mapping/: edit it there and run `kmap export`'))
    for rel in stale_files(ctx, gen):
        problems.append(dbmod.Problem(rel, 'is in a generated folder but no longer generated: run `kmap export`'))
    if offline:
        for bid in ctx.ws.builds:
            committed = committed_signatures(ctx, bid)
            for e in db.symbols(bid):
                if dbmod.exported(e) and e['_kind'] != 'global' and not committed.get(e['name'], (None,))[0]:
                    problems.append(dbmod.Problem(f'symbols/{bid}.toml', f'{e["name"]} has no signature yet: run '
                                                                         '`kmap export` where the game files are'))


def cmd_export(ctx, force=False, offline=False):
    from . import rules
    db = dbmod.load(ctx)
    problems = list(db.problems)
    for check in rules.ALL_CHECKS:
        check(db, problems)
    if problems and not force:
        for p in problems:
            print(f'FAIL {p}')
        raise KmapError(f'{len(problems)} problem(s) in mapping/: fix them first (or export --force)')
    gen = generate(ctx, db, offline)
    changed = [rel for rel, text in sorted(gen.items()) if write_if_changed(ctx.repo / rel, text)]
    for rel in stale_files(ctx, gen):
        (ctx.repo / rel).unlink()
        changed.append(f'{rel} (removed)')
    for rel in changed:
        say(f'wrote {rel}')
    say(f'kmap export: {len(gen)} artifact(s), {len(changed)} changed' + (' (offline: signatures kept)' if offline else ''))
    return 0
