"""Project tasks inside Ghidra: import + auto-analysis (kmap init), function-start lists, decompilation."""
import time
from pathlib import Path

from .common import function_starts, monitor, program_context, project_context, transaction, va

# cube::GameController::update (about 83 KB of code) takes several minutes and its answer is over the default
# 50 MB decompiler response limit
DECOMPILE_TIMEOUT = 1800         # seconds per function
DECOMPILE_PAYLOAD_MB = 1024


def _apply_options(program, options):
    import pyghidra
    props = pyghidra.analysis_properties(program)
    known = set(str(n) for n in props.getOptionNames())
    unknown = [n for n in options if n not in known]
    if unknown:
        raise ValueError(f'unknown analysis option(s) {unknown} for this Ghidra; check [analysis.options] in '
                         'mapping/workspace.toml')
    with transaction(program, 'kmap analysis options'):
        for name, value in options.items():
            if isinstance(value, bool):
                props.setBoolean(name, value)
            elif isinstance(value, int):
                props.setInt(name, value)
            else:
                props.setString(name, str(value))


def task_init(req):
    import pyghidra
    from java.io import File
    from ghidra.program.model.lang import CompilerSpecID, LanguageID
    from ghidra.program.util import DefaultLanguageService
    args = req['args']
    out = {'builds': {}}
    with project_context(args['project'], create=True) as project:
        for b in args['builds']:
            t0 = time.time()
            root = project.getRootFolder()
            old = root.getFile(b['id'])
            if old:
                old.delete()
            lang = DefaultLanguageService.getLanguageService().getLanguage(LanguageID(args['language']))
            comp = lang.getCompilerSpecByID(CompilerSpecID(args['compiler']))
            program = project.importProgram(File(b['path']), lang, comp)
            if program is None:
                raise RuntimeError(f'Ghidra could not import {b["path"]}')
            try:
                _apply_options(program, args['options'])
                print(f'kmap: analysing {b["id"]} (this takes a while)', flush=True)
                pyghidra.analyze(program)
                project.saveAs(program, '/', b['id'], True)
                starts = function_starts(program)
            finally:
                project.close(program)
            out['builds'][b['id']] = {'functions': len(starts), 'starts': starts,
                                      'seconds': round(time.time() - t0)}
            print(f'kmap: {b["id"]}: {len(starts)} functions after {round(time.time() - t0)} s', flush=True)
    return out


def task_function_starts(req):
    args = req['args']
    with project_context(args['project']) as project:
        out = {}
        for bid in args['builds']:
            with program_context(project, bid) as program:
                out[bid] = function_starts(program)
    return {'starts': out}


def task_decompile(req):
    """Decompiles the requested function addresses into args['out'] (under $KMAP_HOME/decomp/)."""
    from ghidra.app.decompiler import DecompInterface, DecompileOptions
    args = req['args']
    out_dir = Path(args['out'])
    written = []
    with project_context(args['project']) as project, program_context(project, args['build']) as program:
        di = DecompInterface()
        options = DecompileOptions()
        options.setMaxPayloadMBytes(DECOMPILE_PAYLOAD_MB)
        di.setOptions(options)
        di.openProgram(program)
        fm = program.getFunctionManager()
        from .common import addr
        for a in args['addresses']:
            f = fm.getFunctionAt(addr(program, a))
            if f is None:
                f = fm.getFunctionContaining(addr(program, a))
            if f is None:
                print(f'kmap: no function at 0x{a:X}', flush=True)
                continue
            res = di.decompileFunction(f, DECOMPILE_TIMEOUT, monitor())
            if not res.decompileCompleted():
                print(f'kmap: decompiling {f.getName()} failed: {res.getErrorMessage()}', flush=True)
                continue
            name = str(f.getName(True)).replace('::', '__')
            safe = ''.join(c if c.isalnum() or c in '_-.~' else '_' for c in name)
            p = out_dir / f'{safe}@{va(f.getEntryPoint()):08X}.c'
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(f'// {f.getName(True)} at 0x{va(f.getEntryPoint()):X} ({args["build"]})\n'
                         '// Local reading aid generated by kmap decompile. Never commit or share this file.\n'
                         + str(res.getDecompiledFunction().getC()), encoding='utf-8')
            written.append(str(p))
        di.dispose()
    return {'written': written}
