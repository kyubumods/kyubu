"""kmap report: mapping/survey-summary.md, the coverage counts per build and subsystem.

The survey's own numbers (functions, library code, RTTI classes, correlation) are kept in the file as a
machine-readable comment, so `kmap check --offline` can rebuild the summary from mapping/ alone and flag it
as stale; the full check uses the fresh survey numbers when the survey is present."""
import json
import re
from collections import Counter

from . import db as dbmod
from .util import KmapError, say, write_if_changed

SUMMARY = 'mapping/survey-summary.md'
MARK = re.compile(r'<!-- kmap-survey (\{.*\}) -->', re.S)
EH = 'msvc-eh'   # compiler-generated exception-handling funclets: shown apart from real library code


def _load(path):
    return json.loads(path.read_text(encoding='utf-8'))


def survey_numbers(ctx):
    """The survey's numbers from $KMAP_HOME/survey/, or None when a build has not been surveyed."""
    out = {}
    for bid in ctx.ws.builds:
        d = ctx.survey_dir / bid
        try:
            funcs, libs, rtti = (_load(d / f) for f in ('functions.json', 'libraries.json', 'rtti.json'))
        except FileNotFoundError:
            return None
        out[bid] = {'functions': len(funcs), 'library': libs['counts'], 'rtti_types': rtti['types'],
                    'rtti_with_vtables': sum(1 for c in rtti['classes'] if c['vtables']),
                    'rtti_with_sizes': sum(1 for c in rtti['classes'] if c['sizes'])}
    try:
        corr = _load(ctx.survey_dir / 'correlation.json')
        out['correlation'] = {'matched': len(corr['matches']), 'server_functions': corr['server_functions'],
                              'by_matcher': corr['counts']}
    except FileNotFoundError:
        pass
    return out


def committed_numbers(ctx):
    p = ctx.repo / SUMMARY
    if not p.is_file():
        return None
    m = MARK.search(p.read_text(encoding='utf-8'))
    return json.loads(m.group(1)) if m else None


def _function_rows(n):
    if 'functions' not in n:
        return ['| total (Ghidra analysis) | ? |']
    lib = dict(n['library'])
    eh = lib.pop(EH, 0)
    libsum = sum(lib.values())
    return [f'| total (Ghidra analysis) | {n["functions"]} |',
            '| library code (' + ', '.join(f'{k} {v}' for k, v in sorted(lib.items())) + f') | {libsum} |',
            f'| exception-handling funclets (`{EH}`, compiler-generated) | {eh} |',
            f'| game code | {n["functions"] - libsum - eh} |']


def render(ctx, db, nums):
    ws = ctx.ws
    lines = ['# Survey summary', '',
             f'Generated by `kmap report` from the survey of both builds (Ghidra {ws.ghidra.version}) and from '
             '`mapping/`. Do not edit: `kmap check` fails when this file is stale.', '']
    types = {t['name']: t for t in db.types}
    for bid in ws.builds:
        n = nums.get(bid, {})
        funcs = [e for e in db.functions(bid) if e.get('kind', 'function') == 'function']
        classes = db.classes(bid)
        sized = sum(1 for c in classes if c.get('size') or (types.get(c['name']) or {}).get('size'))
        fielded = sum(1 for c in classes if (types.get(c['name']) or {}).get('field'))
        lines += [f'## {bid} ({ws.build(bid).file})', '', '| Functions | Count |', '|---|---:|',
                  *_function_rows(n),
                  f'| named in mapping/ | {len({e["address"] for e in funcs})} |',
                  f'| with a prototype | {len({e["address"] for e in funcs if e.get("prototype")})} |', '',
                  '| Classes | Count |', '|---|---:|', f'| RTTI types | {n.get("rtti_types", "?")} |',
                  f'| RTTI types with vtables | {n.get("rtti_with_vtables", "?")} |',
                  f'| RTTI types with a size from `operator new` | {n.get("rtti_with_sizes", "?")} |',
                  f'| in classes.toml | {len(classes)} |', f'| with a size in mapping/ | {sized} |',
                  f'| with fields in mapping/ | {fielded} |', '',
                  '| Subsystem | Entries | verified | candidate | guess | functions | with prototype | classes |',
                  '|---|---:|---:|---:|---:|---:|---:|---:|']
        per = {s: Counter() for s in ws.subsystems}
        for e in db.symbols(bid):
            c = per.setdefault(e.get('subsystem'), Counter())
            c['entries'] += 1
            c[e.get('status')] += 1
            if e['_kind'] == 'function' and e.get('kind', 'function') == 'function':
                c['functions'] += 1
                c['typed'] += bool(e.get('prototype'))
        for c in classes:
            per.setdefault(c.get('subsystem', 'core'), Counter())['classes'] += 1
        for s in ws.subsystems:
            c = per[s]
            lines.append(f'| {s} | {c["entries"]} | {c["verified"]} | {c["candidate"]} | {c["guess"]} | '
                         f'{c["functions"]} | {c["typed"]} | {c["classes"]} |')
        lines.append('')
    lines += ['## Types and enums (shared by both builds)', '', '| | Entries | verified | candidate | guess | fields |',
              '|---|---:|---:|---:|---:|---:|']
    for label, items in (('types', db.types), ('enums', db.enums)):
        c = Counter(e.get('status') for e in items)
        nf = sum(len(e.get('field', [])) + len(e.get('value', [])) for e in items)
        lines.append(f'| {label} | {len(items)} | {c["verified"]} | {c["candidate"]} | {c["guess"]} | {nf} |')
    lines.append('')
    corr = nums.get('correlation')
    if corr:
        lines += ['## Cross-build correlation', '',
                  f'{corr["matched"]} of {corr["server_functions"]} `Server.exe` functions are matched to a `Cube.exe` '
                  'function (' + ', '.join(f'{k}: {v}' for k, v in sorted(corr['by_matcher'].items())) + ').', '']
    lines.append(f'<!-- kmap-survey {json.dumps(nums, sort_keys=True)} -->')
    return '\n'.join(lines) + '\n'


def cmd_report(ctx):
    nums = survey_numbers(ctx)
    if nums is None:
        raise KmapError('no survey in $KMAP_HOME/survey: run `kmap survey` first')
    db = dbmod.load(ctx)
    text = render(ctx, db, nums)
    changed = write_if_changed(ctx.repo / SUMMARY, text)
    say(f'{"wrote" if changed else "unchanged:"} {SUMMARY}')
    return 0


def check_summary(ctx, db, problems, offline=True):
    p = ctx.repo / SUMMARY
    if not p.is_file():
        return
    nums = (None if offline else survey_numbers(ctx)) or committed_numbers(ctx)
    if nums is None:
        problems.append(dbmod.Problem(SUMMARY, 'has no survey numbers: run `kmap survey` and `kmap report`'))
        return
    if p.read_text(encoding='utf-8').replace('\r\n', '\n') != render(ctx, db, nums):
        problems.append(dbmod.Problem(SUMMARY, 'is stale: run `kmap report` (it follows mapping/ and the survey)'))
