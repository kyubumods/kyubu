#!/usr/bin/env python3
"""symgen - generate and check Kyubu symbol maps.

  symgen.py make <exe> <spec.toml> <out.toml>
      spec.toml lists [[symbol]] entries with name/address/convention/status/notes (no signature).
      Writes out.toml with a byte signature for each symbol (relocated dwords wildcarded).

  symgen.py find <exe> <symbols.toml> <build-id> <out.toml>
      Looks for every symbol of symbols.toml in another executable by its signature and writes a
      map for that build (address filled in when the signature matches exactly once; status becomes
      "candidate" so a human confirms it).

  symgen.py check <exe> <symbols.toml>
      Verifies every symbol of a map against an executable (the binary-contract check).
"""
import sys
import tomllib
import pefile

PREFERRED = 0x400000


def load_exe(path):
    pe = pefile.PE(path)
    text = next(s for s in pe.sections if s.Name.rstrip(b'\0') == b'.text')
    relocs = set()
    if hasattr(pe, 'DIRECTORY_ENTRY_BASERELOC'):
        for blk in pe.DIRECTORY_ENTRY_BASERELOC:
            for e in blk.entries:
                if e.type == 3:
                    relocs.add(e.rva)
    return pe, text, relocs


def sig_at(pe, text, relocs, rva, n=20):
    data = pe.get_data(rva, n)
    wild = set()
    for r in relocs:
        if rva - 3 <= r < rva + n:
            for k in range(4):
                wild.add(r + k)
    return ' '.join('??' if rva + i in wild else f'{b:02X}' for i, b in enumerate(data))


def parse_sig(s):
    return [None if t in ('?', '??') else int(t, 16) for t in s.split()]


def match(pe, text, rva, sig):
    data = pe.get_data(rva, len(sig))
    return all(s is None or s == b for s, b in zip(sig, data))


def scan(pe, text, sig, limit=2):
    data = text.get_data()
    base = text.VirtualAddress
    first = next(i for i, s in enumerate(sig) if s is not None)
    hits = []
    start = 0
    while True:
        i = data.find(bytes([sig[first]]), start)
        if i < 0 or len(hits) >= limit:
            break
        off = i - first
        if off >= 0 and all(s is None or (off + k < len(data) and data[off + k] == s) for k, s in enumerate(sig)):
            hits.append(base + off)
        start = i + 1
    return hits


def fmt_symbol(d):
    out = ['[[symbol]]']
    for k in ('name', 'address', 'signature', 'convention', 'status', 'notes'):
        if k not in d:
            continue
        v = d[k]
        out.append(f'{k} = 0x{v:X}' if k == 'address' else f'{k} = "{v}"')
    return '\n'.join(out)


def cmd_make(exe, spec, out):
    pe, text, relocs = load_exe(exe)
    s = tomllib.load(open(spec, 'rb'))
    lines = [f'# Generated by tools/symgen.py from {spec}. Addresses at preferred base 0x400000.',
             f'build = "{s["build"]}"', '']
    for sym in s['symbol']:
        d = dict(sym)
        d['signature'] = sig_at(pe, text, relocs, d['address'] - PREFERRED, d.pop('sig_len', 20))
        lines += [fmt_symbol(d), '']
    open(out, 'w').write('\n'.join(lines))
    print(f'wrote {out}: {len(s["symbol"])} symbols')


def cmd_find(exe, symbols, build, out):
    pe, text, relocs = load_exe(exe)
    s = tomllib.load(open(symbols, 'rb'))
    lines = [f'# Generated by tools/symgen.py find from {symbols}; every entry needs human confirmation.',
             f'build = "{build}"', '']
    found = 0
    for sym in s['symbol']:
        if 'signature' not in sym:
            continue
        hits = scan(pe, text, parse_sig(sym['signature']))
        if len(hits) == 1:
            d = dict(sym)
            d['address'] = hits[0] + PREFERRED
            d['status'] = 'candidate'
            d['notes'] = f'found by signature from {s["build"]} ' + sym.get('notes', '')
            lines += [fmt_symbol(d), '']
            found += 1
            print(f'  found   {sym["name"]} at 0x{hits[0] + PREFERRED:X}')
        else:
            print(f'  {"missing" if not hits else "ambiguous"} {sym["name"]}')
    open(out, 'w').write('\n'.join(lines))
    print(f'wrote {out}: {found} symbols')


def cmd_check(exe, symbols):
    pe, text, relocs = load_exe(exe)
    s = tomllib.load(open(symbols, 'rb'))
    bad = 0
    for sym in s['symbol']:
        sig = parse_sig(sym.get('signature', ''))
        if 'address' in sym:
            rva = sym['address'] - PREFERRED
            inside = text.VirtualAddress <= rva < text.VirtualAddress + text.Misc_VirtualSize
            ok = inside and (not sig or match(pe, text, rva, sig))
            state = 'ok' if ok else ('mismatch' if inside else 'outside .text')
        else:
            hits = scan(pe, text, sig)
            ok = len(hits) == 1
            state = 'ok' if ok else ('not found' if not hits else 'ambiguous')
        verified = sym.get('status') == 'verified'
        if not ok and verified:
            bad += 1
        print(f'  {state:13} {sym.get("status", "candidate"):9} {sym["name"]}')
    print('contract check', 'FAILED' if bad else 'passed')
    return 1 if bad else 0


if __name__ == '__main__':
    a = sys.argv
    if len(a) >= 5 and a[1] == 'make':
        cmd_make(a[2], a[3], a[4])
    elif len(a) >= 6 and a[1] == 'find':
        cmd_find(a[2], a[3], a[4], a[5])
    elif len(a) >= 4 and a[1] == 'check':
        sys.exit(cmd_check(a[2], a[3]))
    else:
        print(__doc__)
        sys.exit(1)
